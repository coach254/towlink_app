import 'package:flutter/material.dart';
import 'package:firebase_core/firebase_core.dart';

import 'firebase_options.dart'; // Generated by flutterfire configure

import 'screens/auth/welcome_screen.dart';
import 'screens/customer/customer_home_screen.dart';
import 'screens/driver/driver_home_screen.dart';
import 'services/session_service.dart';
import 'theme/app_theme.dart';

void main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  runApp(const TowLinkApp());
}

class TowLinkApp extends StatelessWidget {
  const TowLinkApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'TowLink Ghana',
      debugShowCheckedModeBanner: false,
      theme: AppTheme.light(),
      darkTheme: AppTheme.dark(), // <-- Enables Dark Theme
      themeMode: ThemeMode.system, // <-- Follows device settings
      home: const _RootGate(),
    );
  }
}

class _RootGate extends StatefulWidget {
  const _RootGate();

  @override
  State<_RootGate> createState() => _RootGateState();
}

class _RootGateState extends State<_RootGate> {
  late Future<Widget> _initial;

  @override
  void initState() {
    super.initState();
    _initial = _decideStartScreen();
  }

  Future<Widget> _decideStartScreen() async {
    final role = await SessionService.loadRole();
    if (role == UserRole.customer) {
      return const CustomerHomeScreen();
    }
    if (role == UserRole.driver) {
      final id = await SessionService.loadDriverId();
      if (id != null) return DriverHomeScreen(driverId: id);
    }
    return const WelcomeScreen();
  }

  @override
  Widget build(BuildContext context) {
    return FutureBuilder<Widget>(
      future: _initial,
      builder: (context, snapshot) {
        if (!snapshot.hasData) {
          return const Scaffold(
            backgroundColor: AppColors.primary,
            body: Center(child: CircularProgressIndicator(color: Colors.white)),
          );
        }
        return snapshot.data!;
      },
    );
  }
}
